"""Demo helper: feed real images through the running app so the live dashboard has activity.

Each image goes through the normal /api/classify endpoint, so the records, bin loads, alerts and
collections are produced by the real application logic and the real model. The only artificial part
is that the traffic is generated by this script. It uses a clearly named demo user.

Usage (server must be running):
    python scripts/demo_traffic.py --count 40 --delay 2            # random test images
    python scripts/demo_traffic.py --count 10 --location "Canteen"
Remove demo data afterwards (fresh demo databases only):
    python scripts/demo_traffic.py --cleanup
"""
import argparse
import random
import re
import sys
import time
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
DEMO_EMAIL = "demo.traffic@example.com"
DEMO_PASSWORD = "DemoTraffic#2026"


def csrf_from(html):
    m = re.search(r'name="csrf-token" content="([^"]+)"', html) or re.search(r'name="csrf_token" value="([^"]+)"', html)
    if not m:
        sys.exit("Could not find a CSRF token. Is the server running at the given URL?")
    return m.group(1)


def run(args):
    images = sorted(Path(args.data).glob("*/*.jpg"))
    if not images:
        sys.exit(f"No images found in {args.data}. Run ml/prepare_dataset.py first.")
    s = requests.Session()
    base = args.url.rstrip("/")

    tok = csrf_from(s.get(base + "/register", timeout=15).text)
    s.post(base + "/register", data={"csrf_token": tok, "name": "Demo Traffic", "email": DEMO_EMAIL,
                                     "password": DEMO_PASSWORD, "confirm": DEMO_PASSWORD}, timeout=15)  # ok if it exists
    tok = csrf_from(s.get(base + "/login", timeout=15).text)
    r = s.post(base + "/login", data={"csrf_token": tok, "email": DEMO_EMAIL, "password": DEMO_PASSWORD}, timeout=15)
    if "/login" in r.url:
        sys.exit("Demo login failed.")
    page = s.get(base + "/classify", timeout=15).text
    token = csrf_from(page)
    locs = dict((name, int(v)) for v, name in re.findall(r'<option value="(\d+)">([^<]+)</option>', page))
    if args.location:
        if args.location not in locs:
            sys.exit(f"Unknown location. Choose from: {', '.join(locs)}")
        choices = [locs[args.location]]
    else:
        choices = list(locs.values())

    for i in range(args.count):
        img = random.choice(images)
        with open(img, "rb") as f:
            resp = s.post(base + "/api/classify", headers={"X-CSRFToken": token},
                          data={"location_id": random.choice(choices)}, files={"image": (img.name, f, "image/jpeg")}, timeout=120)
        j = resp.json()
        if resp.ok:
            print(f"[{i + 1}/{args.count}] true={img.parent.name:8s} predicted={j['category']:8s} {j['confidence']:6.2f}%  -> {j['bin']} ({j['location']})")
        else:
            print(f"[{i + 1}/{args.count}] error {resp.status_code}: {j.get('error')}")
        time.sleep(args.delay)


def cleanup():
    sys.path.insert(0, str(ROOT))
    import os
    from app import create_app
    from app.extensions import db
    from app.models import Alert, BinCompartment, CollectionRecord, SmartBin, User, WasteRecord

    app = create_app()
    with app.app_context():
        user = User.query.filter_by(email=DEMO_EMAIL).first()
        if not user:
            print("No demo user found."); return
        recs = WasteRecord.query.filter_by(user_id=user.id).all()
        for r in recs:
            if r.compartment_id:
                c = db.session.get(BinCompartment, r.compartment_id)
                c.current_load = max(0.0, round(c.current_load - r.estimated_volume, 3))
            path = Path(app.config["UPLOAD_FOLDER"]) / r.image_filename
            if path.exists():
                path.unlink()
            db.session.delete(r)
        db.session.flush()
        cfg = app.config
        for a in Alert.query.filter_by(resolved=False).all():  # alerts no longer justified
            if a.compartment_id and db.session.get(BinCompartment, a.compartment_id).fill_percent < cfg["ALERT_PERCENT"]:
                db.session.delete(a)
        for c in CollectionRecord.query.filter_by(status="pending").all():
            if db.session.get(SmartBin, c.bin_id).max_fill_percent < cfg["ALERT_PERCENT"]:
                db.session.delete(c)
        db.session.delete(user)
        db.session.commit()
        print(f"Removed demo user and {len(recs)} demo records.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", default="http://localhost:8000")
    ap.add_argument("--data", default=str(ROOT / "data" / "dataset" / "test"))
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("--delay", type=float, default=2.0)
    ap.add_argument("--location", default=None)
    ap.add_argument("--cleanup", action="store_true")
    a = ap.parse_args()
    cleanup() if a.cleanup else run(a)
